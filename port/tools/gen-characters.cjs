// Generates src/characters-data.ts from js/characters.js (values after its post-processing) and lists every
// move callback in src/move-handlers.reference.js for hand porting. Run from port/: node tools/gen-characters.cjs
const vm = require("vm");
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..", "..");
const ctx = { Math, console, Object, Array, JSON };
const stub = new Proxy(function () {}, { get: () => stub, apply: () => stub });
for (const name of ["Sound", "Items", "Sprites", "document", "window", "Image"]) ctx[name] = stub;
vm.createContext(ctx);
vm.runInContext(
  ["js/util.js", "js/characters.js"].map((f) => fs.readFileSync(path.join(root, f), "utf8")).join("\n") + ";globalThis.__C = CHARACTERS;",
  ctx,
);
const characters = Object.values(ctx.__C);

const handlerNames = new Map();
const handlerOrder = [];
const handlerFor = (fn, owner, move, field) => {
  if (!handlerNames.has(fn)) {
    const name = `${owner}_${move}_${field}`;
    handlerNames.set(fn, name);
    handlerOrder.push({ name, field, source: fn.toString() });
  }
  return `handlers.${handlerNames.get(fn)}`;
};

const num = (v) => (Number.isInteger(v) ? String(v) : String(+v.toFixed(6)));
const str = (v) => JSON.stringify(v);
const limb = (v) => `[${v.map(num).join(", ")}]`;
const pose = (p) => {
  if (!p) return "{}";
  const fields = [];
  for (const key of ["lean", "crouch", "rot", "yOff", "headTilt", "scale"]) if (p[key] !== undefined) fields.push(`${key}: ${num(p[key])}`);
  for (const key of ["armF", "armB", "legF", "legB"]) if (p[key] !== undefined) fields.push(`${key}: ${limb(p[key])}`);
  if (p.prop !== undefined) fields.push(`prop: ${str(p.prop)}`);
  return `{ ${fields.join(", ")} }`;
};
const hitbox = (h) => {
  const known = new Set(["s", "e", "x", "y", "r", "d", "a", "b", "k", "g", "grab", "fkb", "fx"]);
  for (const key of Object.keys(h)) if (!known.has(key)) throw new Error(`unknown hitbox field ${key}`);
  return `hb(${["s", "e", "x", "y", "r", "d", "a", "b", "k", "g"].map((k) => num(h[k] ?? 0)).join(", ")}, ${!!h.grab}, ${num(h.fkb ?? 0)}, ${str(h.fx ?? "")})`;
};
const moveFields = ["frames", "iasa", "aerial", "special", "smash", "final", "charge", "landLag", "landKeep", "helplessAir", "crouchMove", "slideOff", "intangible", "next", "nextWin", "ledgeFrom", "as", "ae"];
const move = (m, owner, key) => {
  const known = new Set([...moveFields, "id", "hitboxes", "poses", "update", "anim", "drawOver"]);
  for (const field of Object.keys(m)) if (!known.has(field)) throw new Error(`unknown move field ${field} in ${owner}.${key}`);
  const lines = [`id: ${str(key)}`];
  lines.push(`frames: ${num(m.frames)}`);
  lines.push(`iasa: ${num(m.iasa ?? 0)}`);
  lines.push(`hitboxes: [${(m.hitboxes || []).map(hitbox).join(", ")}]`);
  lines.push(`poses: ${m.poses ? `{ wind: ${pose(m.poses.wind)}, hit: ${pose(m.poses.hit)} }` : "null"}`);
  for (const flag of ["aerial", "special", "smash", "final", "landKeep", "helplessAir", "crouchMove"]) lines.push(`${flag}: ${!!m[flag]}`);
  lines.push(`slideOff: ${m.slideOff === undefined ? true : !!m.slideOff}`);
  for (const value of ["charge", "landLag", "ledgeFrom", "as", "ae"]) lines.push(`${value}: ${num(m[value] ?? 0)}`);
  lines.push(`intangible: ${m.intangible ? limb(m.intangible) : "[]"}`);
  lines.push(`next: ${str(m.next ?? "")}`);
  lines.push(`nextWin: ${m.nextWin ? limb(m.nextWin) : "[]"}`);
  for (const field of ["update", "anim", "drawOver"]) {
    lines.push(`${field}: ${typeof m[field] === "function" ? handlerFor(m[field], owner, key, field) : "null"}`);
  }
  return `{ ${lines.join(", ")} }`;
};
const colors = (c) => `{ ${["main", "dark", "accent", "pants", "skin", "glow", "shirt", "stripe", "sole"].map((k) => `${k}: ${str(c[k] ?? "")}`).join(", ")} }`;
const statKeys = ["walk", "dash", "dashInit", "dashFrames", "run", "traction", "airSpeed", "airAccel", "airFriction", "gravity", "maxFall", "fastFall", "jump", "shortHop", "djump", "jumpsquat", "jumpMaxVX", "airJumps", "airdodge", "float", "weight"];

let out = `// Generated by tools/gen-characters.cjs from js/characters.js. Edit the source data there, or port callbacks in move-handlers.ts.
import * as handlers from "./move-handlers";
import { type Character, H, type Hitbox, type Move } from "./types";

function hb(s: number, e: number, x: number, y: number, r: number, d: number, a: number, b: number, k: number, g: number, grab: boolean, fkb: number, fx: string): Hitbox {
  return H(s, e, x, y, r, d, a, b, k, { g, grab, fkb, fx });
}

function moves(list: Move[]): Map<string, Move> {
  const map = new Map<string, Move>();
  for (const m of list) map.set(m.id, m);
  return map;
}

export const CHARACTERS: Character[] = [\n`;
for (const c of characters) {
  for (const key of statKeys) if (typeof c.stats[key] !== "number") throw new Error(`missing stat ${key} for ${c.id}`);
  out += `  {
    id: ${str(c.id)},
    name: ${str(c.name)},
    title: ${str(c.title)},
    colors: ${colors(c.colors)},
    alt: ${colors(c.alt)},
    selectStats: [${Object.entries(c.selectStats).map(([label, value]) => `{ label: ${str(label)}, value: ${num(value)} }`).join(", ")}],
    moveList: [${c.moveList.map(([input, text]) => `{ input: ${str(input)}, text: ${str(text)} }`).join(", ")}],
    stats: { ${statKeys.map((k) => `${k}: ${num(c.stats[k])}`).join(", ")} },
    throws: { ${["f", "b", "u", "d"].map((k) => `${k}: { d: ${num(c.throws[k].d)}, a: ${num(c.throws[k].a)}, b: ${num(c.throws[k].b)}, k: ${num(c.throws[k].k)} }`).join(", ")} },
    moves: moves([
${Object.entries(c.moves).map(([key, m]) => `      ${move(m, c.id, key)},`).join("\n")}
    ]),
  },\n`;
}
out += "];\n";
fs.writeFileSync(path.join(__dirname, "..", "src", "characters-data.ts"), out);

let reference = "// Original move callbacks from js/characters.js, one per handler in move-handlers.ts. Reference only, not compiled.\n";
for (const h of handlerOrder) reference += `\n// ${h.name} (${h.field})\n${h.source}\n`;
fs.writeFileSync(path.join(__dirname, "..", "src", "move-handlers.reference.js"), reference);
console.log(`${characters.length} characters, ${handlerOrder.length} unique callbacks`);
